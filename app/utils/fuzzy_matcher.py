# ==================== 1. НОРМАЛИЗАЦИЯ КИРИЛЛИЦЫ ====================

def normalize_cyrillic(text: str) -> str:
    """
    Нормализация кириллического текста для fuzzy-matching.
    
    Правила:
    - Приведение к нижнему регистру
    - ё → е
    - Удаление лишних пробелов
    - Нормализация дефисов
    """
    if not text:
        return ""
    
    text = text.lower().strip()
    
    # ё → е
    text = text.replace("ё", "е")
    
    # Нормализация дефисов и пробелов
    text = re.sub(r'[-–—]', '-', text)  # Унификация дефисов
    text = re.sub(r'\s+', ' ', text)     # Удаление лишних пробелов
    
    return text


def normalize_for_comparison(text: str) -> str:
    """
    Расширенная нормализация для сравнения.
    
    Дополнительно:
    - Убирает окончания падежей
    - Убирает мягкий знак в конце
    """
    text = normalize_cyrillic(text)
    
    # Убираем типичные окончания
    endings = ['ы', 'и', 'у', 'а', 'е', 'ю', 'ой', 'ей', 'ью', 'ом', 'ем', 'ах', 'ях']
    for ending in sorted(endings, key=len, reverse=True):
        if len(text) > len(ending) + 2 and text.endswith(ending):
            text = text[:-len(ending)]
            break
    
    return text


