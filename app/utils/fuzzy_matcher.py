# ==================== 3. FUZZY MATCHING ФУНКЦИИ ====================

def fuzzy_match(text: str, choices: List[str], threshold: int = 70) -> Optional[Tuple[str, int]]:
    """
    Fuzzy matching с использованием rapidfuzz.
    
    Args:
        text: Текст для поиска
        choices: Список вариантов
        threshold: Минимальный порог совпадения (0-100)
        
    Returns:
        Tuple(best_match, score) или None
    """
    if not text or not choices:
        return None
    
    text = normalize_cyrillic(text)
    
    if RAPIDFUZZ_AVAILABLE:
        result = process.extractOne(text, choices, scorer=fuzz.WRatio)
        if result and result[1] >= threshold:
            return (result[0], result[1])
    else:
        # Fallback: простое сравнение
        best_match = None
        best_score = 0
        for choice in choices:
            choice_norm = normalize_cyrillic(choice)
            if text == choice_norm:
                return (choice, 100)
            if text in choice_norm or choice_norm in text:
                score = 80
                if score > best_score:
                    best_score = score
                    best_match = choice
        if best_match and best_score >= threshold:
            return (best_match, best_score)
    
    return None


def fix_typo(text: str, typo_dict: Dict[str, str]) -> str:
    """
    Исправление опечатки по словарю.
    
    Args:
        text: Текст с возможной опечаткой
        typo_dict: Словарь опечаток {typo: correct}
        
    Returns:
        Исправленный текст
    """
    text_norm = normalize_cyrillic(text)
    
    # Точное совпадение
    if text_norm in typo_dict:
        return typo_dict[text_norm]
    
    # Fuzzy-поиск по ключам словаря
    if RAPIDFUZZ_AVAILABLE:
        keys = list(typo_dict.keys())
        result = process.extractOne(text_norm, keys, scorer=fuzz.WRatio)
        if result and result[1] >= 80:
            return typo_dict[result[0]]
    
    return text


