def smart_match_region(
    user_input: str, 
    tourvisor_regions: List[Dict[str, Any]],
    threshold: int = 70
) -> Optional[Tuple[int, str, int]]:
    """
    Умный поиск региона по вводу пользователя.
    
    Алгоритм:
    1. Нормализация ввода
    2. Исправление опечаток по словарю
    3. Fuzzy-поиск по справочнику Tourvisor
    
    Args:
        user_input: Ввод пользователя ("анталия")
        tourvisor_regions: Список регионов из Tourvisor API
        threshold: Порог совпадения
        
    Returns:
        Tuple(region_id, region_name, score) или None
    """
    if not user_input or not tourvisor_regions:
        return None
    
    # Шаг 1: Нормализация
    normalized = normalize_cyrillic(user_input)
    
    # Шаг 2: Исправление опечаток
    corrected = normalize_resort(normalized)
    logger.info(f"🔧 FUZZY: '{user_input}' → normalized='{normalized}' → corrected='{corrected}'")
    
    # Шаг 3: Поиск по Tourvisor
    region_names = [r["name"].lower() for r in tourvisor_regions]
    
    # Сначала ищем исправленное
    for r in tourvisor_regions:
        r_name_lower = r["name"].lower()
        r_name_norm = normalize_cyrillic(r["name"])
        
        # Точное совпадение
        if corrected == r_name_lower or corrected == r_name_norm:
            logger.info(f"✅ FUZZY: Точное совпадение '{corrected}' → {r['name']} (ID={r['id']})")
            return (r["id"], r["name"], 100)
    
    # Fuzzy-поиск
    if RAPIDFUZZ_AVAILABLE:
        result = process.extractOne(corrected, region_names, scorer=fuzz.WRatio)
        if result and result[1] >= threshold:
            # Найти ID по имени
            for r in tourvisor_regions:
                if r["name"].lower() == result[0]:
                    logger.info(f"✅ FUZZY: Fuzzy match '{corrected}' → {r['name']} (ID={r['id']}, score={result[1]})")
                    return (r["id"], r["name"], result[1])
    
    logger.warning(f"⚠️ FUZZY: Не найдено совпадение для '{user_input}' (corrected='{corrected}')")
    return None


